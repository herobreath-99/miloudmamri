export type TranslationKey = keyof (typeof dict)["ar"];
type Key = TranslationKey;

/**
 * Universal text helper that returns the right text based on active language.
 * Guarantees that when `lang === 'dz'`, the Algerian Darija translation is used,
 * or safely falls back to Arabic before French/English.
 */
export function getLocalizedText(
  lang: Lang,
  texts: { ar: string; dz?: string; fr?: string; en?: string },
): string {
  if (lang === "dz" && texts.dz) return texts.dz;
  if (lang === "ar" && texts.ar) return texts.ar;
  if (lang === "fr" && texts.fr) return texts.fr;
  if (lang === "en" && texts.en) return texts.en;
  // Intelligent fallbacks
  if (lang === "dz") return texts.ar || texts.fr || texts.en || "";
  if (lang === "fr") return texts.en || texts.ar || "";
  return texts.ar || texts.en || "";
}

const Ctx = createContext<{
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: Key) => string;
  dir: "rtl" | "ltr";
}>({ lang: "ar", setLang: () => {}, t: (k) => k, dir: "rtl" });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("ar");

  useEffect(() => {
    const stored =
      typeof window !== "undefined" ? (localStorage.getItem("pc_lang") as Lang | null) : null;
    if (stored === "ar" || stored === "dz" || stored === "fr" || stored === "en") {
      setLangState(stored);
    }
  }, []);

  useEffect(() => {
    if (typeof document !== "undefined") {
      document.documentElement.lang = lang;
      document.documentElement.dir = lang === "ar" || lang === "dz" ? "rtl" : "ltr";
    }
  }, [lang]);

  const setLang = (l: Lang) => {
    setLangState(l);
    if (typeof window !== "undefined") localStorage.setItem("pc_lang", l);
  };

  const t = (k: Key) => {
    const currentDict = dict[lang] as Record<string, string> | undefined;
    if (currentDict && currentDict[k]) return currentDict[k];

    // For Darija, fall back to Arabic first so it stays in Arabic script
    if (lang === "dz") {
      const arDict = dict.ar as Record<string, string>;
      if (arDict[k]) return arDict[k];
    }

    const enDict = dict.en as Record<string, string>;
    if (enDict[k]) return enDict[k];
    return k;
  };

  const dir: "rtl" | "ltr" = lang === "ar" || lang === "dz" ? "rtl" : "ltr";

  return <Ctx.Provider value={{ lang, setLang, t, dir }}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
